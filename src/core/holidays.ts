/** 내장 공휴일이 커버하는 마지막 날짜. 이후 기간은 사용자가 직접 휴강일로 등록해야 한다. */
export const HOLIDAY_DATA_END: ISODate = Object.keys(KR_HOLIDAYS).sort().slice(-1)[0]

export const HOLIDAY_RANGE_LABEL = `2025-01-01 ~ ${HOLIDAY_DATA_END}`

/** 자동 휴강용 가상 ClosedDay 목록 (해제된 날짜 제외) */
export function holidayClosures(disabled: ISODate[]): ClosedDay[] {
  const off = new Set(disabled)
  return Object.entries(KR_HOLIDAYS)
    .filter(([date]) => !off.has(date))
    .map(([date, name]) => ({
      id: `holiday:${date}`,
      date,
      reason: name,
      scope: 'all' as const,
    }))
}
